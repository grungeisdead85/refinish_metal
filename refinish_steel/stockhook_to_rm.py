#!/usr/bin/env python3
# stockhook_to_rm.py
# ==========================================
# REFINISH METAL'S COPY OF STOCKHOOK, GENERATED FROM STOCKHOOK
# ==========================================
# WHAT: builds Refinish Metal's built-in copy of Stockhook from the
# standalone Stockhook mod's files. The standalone is the only source:
# change Stockhook, then run this, then publish both.
#
# WHY A COPY AT ALL: RM worlds made before the standalone existed can't add
# a mod, so RM keeps Stockhook built in. A copy written by hand would drift
# from the standalone; a generated one can't.
#
# WHAT CHANGES, AND NOTHING ELSE (stockhook.lua, THE COPIES):
#   * file names        stockhook*.lua -> refinish-stockhook*.lua
#   * script lookups     reqscript / findScript of those names
#   * handler keys       stockhook:core -> refinish_stockhook:core, ...
#   * the _G table       _G.stockhook_mod -> _G.refinish_stockhook_mod
#   * the copy           MOD_ID 'refinish_steel', DEFER_TO 'stockhook'
#                        (WHICH COPY THIS IS): RM's copy stands aside in a
#                        world that also has the standalone
#   * console words      'stockhook status' -> 'refinish-stockhook status'
#   * the guide          the same, for RM's STOCKHOOK_DEFINITIONS.md
#   * vanilla.txt        its opening paragraph, which names the ids
# The DLL, its targets file and its source are copied byte for byte, so
# both mods always ship the same hook files.
#
# Every change is counted, and a change that finds nothing it expects stops
# the run before anything is written: a renamed marker in Stockhook's files
# fails loudly here instead of shipping a copy that half works.
#
# USE (from anywhere):
#   python stockhook_to_rm.py <stockhook folder> <refinish_steel folder>
#   python stockhook_to_rm.py <stockhook folder> <refinish_steel folder> --check
# --check writes nothing: it says whether RM's files are what this would
# write, so a release can be checked before it is published.

import re
import sys
from pathlib import Path

# ---- THE FILES ----
SCRIPTS = ['stockhook.lua', 'stockhook-defs.lua', 'stockhook-rows.lua', 'stockhook-install.lua']
COPIED = ['dfhooks_stockhook.dll', 'stockhook_targets.txt', 'stockhook_dll.cpp']
GUIDE = 'STOCKHOOK_DEFINITIONS.md'
VANILLA = 'stockhook/vanilla.txt'

# ---- THE COPY (stockhook.lua, WHICH COPY THIS IS) ----
# The two lines exactly as Stockhook writes them, and as RM's copy needs them.
COPY_LINES = [
    ("local MOD_ID = 'stockhook'   -- THE COPY: this copy's mod id",
     "local MOD_ID = 'refinish_steel'   -- THE COPY: this copy's mod id"),
    ("local DEFER_TO = nil         -- THE COPY: the mod whose copy runs instead",
     "local DEFER_TO = 'stockhook'   -- THE COPY: the mod whose copy runs instead"),
]

COMMANDS = r'(status|reload|paths|piles|set|type|rows|install|uninstall)'


def rm_name(name):
    """stockhook-defs.lua -> refinish-stockhook-defs.lua."""
    return 'refinish-' + name


def banner(name):
    """Said at the top of every generated script, after its first two lines."""
    return ('-- GENERATED by stockhook_to_rm.py from Stockhook\'s ' + name + ': Refinish\n'
            '-- Metal\'s built-in copy of Stockhook (Stockhook\'s stockhook.lua, THE\n'
            '-- COPIES). Change Stockhook\'s file and generate again; never edit this one.\n')


def sub(text, pattern, repl, what, regex=True, at_least=1, exactly=None):
    """One change, counted. Stops the run when it finds too few."""
    if regex:
        out, n = re.subn(pattern, repl, text)
    else:
        n = text.count(pattern)
        out = text.replace(pattern, repl)
    if exactly is not None and n != exactly:
        sys.exit('stopped: %s: expected exactly %d, found %d' % (what, exactly, n))
    if exactly is None and n < at_least:
        sys.exit('stopped: %s: expected at least %d, found %d' % (what, at_least, n))
    return out


def script(name, text):
    """One Lua script, as RM's copy."""
    if name == 'stockhook.lua':
        for old, new in COPY_LINES:
            text = sub(text, old, new, name + ': the copy line ' + old.split('=')[0].strip(),
                       regex=False, exactly=1)
    # ---- SCRIPT LOOKUPS ----
    text = sub(text, r"reqscript\(\s*'stockhook(-defs|-rows|-install)?'\s*\)",
               r"reqscript('refinish-stockhook\1')", name + ': reqscript', at_least=0)
    text = sub(text, r"pcall\(\s*reqscript\s*,\s*'stockhook(-defs|-rows|-install)?'\s*\)",
               r"pcall(reqscript, 'refinish-stockhook\1')", name + ': pcall(reqscript)', at_least=0)
    text = sub(text, r"findScript\(\s*'stockhook-install'\s*\)",
               "findScript('refinish-stockhook-install')", name + ': findScript',
               at_least=1 if name == 'stockhook-install.lua' else 0)
    # ---- HANDLER KEYS ----
    text = sub(text, "onStateChange['stockhook:", "onStateChange['refinish_stockhook:",
               name + ': handler key', regex=False, exactly=0 if name == 'stockhook-rows.lua' else 1)
    # ---- THE _G TABLE ----
    text = sub(text, '_G.stockhook_mod', '_G.refinish_stockhook_mod', name + ': the _G table',
               regex=False, at_least=1)
    # ---- FILE NAMES IN COMMENTS AND MESSAGES ----
    text = sub(text, r'(?<![\w-])stockhook(-defs|-rows|-install)?\.lua', r'refinish-stockhook\1.lua',
               name + ': file names', at_least=1)
    # ---- CONSOLE WORDS ----
    text = sub(text, r'(?<![\w-])stockhook ' + COMMANDS + r'\b', r'refinish-stockhook \1',
               name + ': console words', at_least=0)
    # ---- WHAT MUST NOT BE LEFT ----
    for leftover in [r"reqscript\(\s*'stockhook", r"onStateChange\['stockhook:", r'_G\.stockhook_mod\b']:
        if re.search(leftover, text):
            sys.exit('stopped: %s: still holds %s' % (name, leftover))
    lines = text.split('\n')
    return '\n'.join(lines[:2]) + '\n' + banner(name) + '\n'.join(lines[2:])


def guide(text):
    """Stockhook's guide, as RM ships it: RM's command name throughout."""
    note = ("In Refinish Metal's copy the command is `refinish-stockhook` instead of\n"
            "`stockhook` (`refinish-stockhook status`, and so on).\n\n")
    text = sub(text, note, '', GUIDE + ': the command note', regex=False, exactly=1)
    text = sub(text, r'`stockhook( [^`]*)?`', r'`refinish-stockhook\1`', GUIDE + ': commands', at_least=1)
    head = ('# Stockhook definition files\n\n'
            '*Stockhook\'s own guide, shipped with Refinish Metal\'s built-in copy of\n'
            'Stockhook. In Refinish Metal the console command is `refinish-stockhook`.*\n')
    return sub(text, '# Stockhook definition files\n', head, GUIDE + ': title', regex=False, exactly=1)


def vanilla(text):
    """Stockhook's own rows, as RM ships them: only the opening paragraph changes."""
    first, sep, rest = text.partition('\n\n')
    if not first.startswith("Stockhook's own definitions") or not sep:
        sys.exit('stopped: %s: its opening paragraph has changed; update vanilla() here' % VANILLA)
    head = ("Stockhook's own definitions: rows that split DF's own stockpile entries.\n"
            "This is Refinish Metal's copy of Stockhook's vanilla.txt, generated by\n"
            "stockhook_to_rm.py: change Stockhook's file and generate again. Here, in\n"
            "RM's folder, the ids are REFINISH_STEEL:COKE, REFINISH_STEEL:CHARCOAL,\n"
            "REFINISH_STEEL:REFINED_COAL, and the generated REFINISH_STEEL:TOOL_<tool\n"
            "id> and REFINISH_STEEL:WOOD_<plant id>_<list>: the ids every RM world has\n"
            "used since 4.1.0, so saved pile settings carry over.")
    return head + sep + rest


def plan(sh, rm):
    """Every file RM's copy should hold: { path in RM: bytes }."""
    out = {}
    for name in SCRIPTS:
        src = (sh / 'scripts_modactive' / name).read_text(encoding='utf-8')
        out['scripts_modactive/' + rm_name(name)] = script(name, src).encode('utf-8')
    for name in COPIED:
        out[name] = (sh / name).read_bytes()
    out[GUIDE] = guide((sh / GUIDE).read_text(encoding='utf-8')).encode('utf-8')
    out[VANILLA] = vanilla((sh / VANILLA).read_text(encoding='utf-8')).encode('utf-8')
    return out


def main():
    args = [a for a in sys.argv[1:] if a != '--check']
    check = '--check' in sys.argv[1:]
    if len(args) != 2:
        sys.exit(__doc__ or 'usage: stockhook_to_rm.py <stockhook folder> <refinish_steel folder> [--check]')
    sh, rm = Path(args[0]), Path(args[1])
    if not (sh / 'info.txt').is_file() or 'ID:stockhook]' not in (sh / 'info.txt').read_text(encoding='utf-8'):
        sys.exit('stopped: %s is not the Stockhook mod folder' % sh)
    if not (rm / 'info.txt').is_file() or 'ID:refinish_steel]' not in (rm / 'info.txt').read_text(encoding='utf-8'):
        sys.exit('stopped: %s is not the Refinish Metal mod folder' % rm)
    files = plan(sh, rm)
    differ = [p for p, data in files.items() if not (rm / p).is_file() or (rm / p).read_bytes() != data]
    if check:
        if differ:
            print('RM\'s copy is NOT current. Differs: ' + ', '.join(sorted(differ)))
            sys.exit(1)
        print('RM\'s copy is current: %d files match Stockhook.' % len(files))
        return
    for p in sorted(files):
        dest = rm / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(files[p])
    print('Wrote %d files into %s (%d changed).' % (len(files), rm, len(differ)))


if __name__ == '__main__':
    main()
